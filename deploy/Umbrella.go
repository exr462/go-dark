// Umbrella describes the one-release deployment: every enabled service's
// chart becomes a subchart of <Application>-umbrella, installed as the
// release named Application.
type Umbrella struct {
	Application string
	Dir         string            // where the umbrella chart is generated (the install dir's charts/)
	Enabled     func(Target) bool // nil enables every target
	Staged      map[string]Staged // per subchart, filled by PrepareUmbrella
}

// UmbrellaValuesFile is the umbrella's values file go-dark writes: every
// subchart's layers nested under its name, plus its enabled switch.
const UmbrellaValuesFile = "values.go-dark.yaml"

// Name is the umbrella chart's name.
func (u Umbrella) Name() string { return u.Application + "-umbrella" }

// ChartDir is the generated chart.
func (u Umbrella) ChartDir() string { return filepath.Join(u.Dir, u.Name()) }

func (u Umbrella) enabled(t Target) bool { return u.Enabled == nil || u.Enabled(t) }

// EnabledTargets filters the waves to the enabled targets.
func (u Umbrella) EnabledTargets(waves [][]Target) [][]Target {
	var out [][]Target
	for _, wave := range waves {
		var kept []Target
		for _, t := range wave {
			if u.enabled(t) {
				kept = append(kept, t)
			}
		}
		if len(kept) > 0 {
			out = append(out, kept)
		}
	}
	return out
}

// PrepareUmbrella (re)generates the umbrella chart: Chart.yaml listing every
// target as a dependency with a <chart>.enabled condition, charts/<chart>
// staged like PrepareChart does (the lcl layering lives inside each
// subchart), and UmbrellaValuesFile nesting each subchart's value layers
// (ConfigFrom values file, the developer's local values, the overlay) under
// its name - all subcharts use the same main/ypto/data keys, so they must
// not be merged at the top level. Disabled targets stay in the chart,
// switched off, so the umbrella's shape doesn't change per run.
func PrepareUmbrella(u *Umbrella, targets []Target, env Env) (Staged, error) {
	dir := u.ChartDir()
	if err := os.RemoveAll(dir); err != nil {
		return Staged{}, err
	}
	if err := os.MkdirAll(filepath.Join(dir, "charts"), 0o755); err != nil {
		return Staged{}, err
	}
	u.Staged = map[string]Staged{}

	var deps []map[string]any
	values := map[string]any{}
	hasDeps := false
	names := map[string]bool{}
	for _, t := range targets {
		if names[t.ChartName] {
			return Staged{}, fmt.Errorf("two services ship a chart named %s", t.ChartName)
		}
		names[t.ChartName] = true
		st, err := PrepareChart(t, filepath.Join(dir, "charts"), env)
		if err != nil {
			return Staged{}, fmt.Errorf("%s: %w", t.Project.Name, err)
		}
		u.Staged[t.ChartName] = st
		hasDeps = hasDeps || st.HasDeps
		deps = append(deps, map[string]any{"name": t.ChartName, "version": ChartVersion(t), "condition": t.ChartName + ".enabled"})

		nested := map[string]any{}
		for _, f := range st.Values {
			layer, err := readYAML(f)
			if err != nil {
				return Staged{}, fmt.Errorf("%s: %w", f, err)
			}
			mergeValues(nested, layer)
		}
		nested["enabled"] = u.enabled(t)
		values[t.ChartName] = nested
	}

	chart := map[string]any{
		"apiVersion":   "v2",
		"name":         u.Name(),
		"description":  "go-dark umbrella: the " + u.Application + " services as subcharts, deployed as one release",
		"type":         "application",
		"version":      LocalChartVersion,
		"dependencies": deps,
	}
	chartYAML, err := yaml.Marshal(chart)
	if err != nil {
		return Staged{}, err
	}
	if err := os.WriteFile(filepath.Join(dir, "Chart.yaml"), chartYAML, 0o644); err != nil {
		return Staged{}, err
	}
	valuesYAML, err := yaml.Marshal(values)
	if err != nil {
		return Staged{}, err
	}
	valuesFile := filepath.Join(dir, UmbrellaValuesFile)
	header := "# Generated by go-dark: each subchart's value layers (" + env.valuesFile() + ", " + LocalValuesFile + ", " + OverlayFile + ") nested under its name.\n"
	if err := os.WriteFile(valuesFile, append([]byte(header), valuesYAML...), 0o644); err != nil {
		return Staged{}, err
	}
	return Staged{Dir: dir, Values: []string{valuesFile}, HasDeps: hasDeps}, nil
}

// mergeValues merges src into dst the way Helm layers values files: maps
// recursively, anything else replaced.
func mergeValues(dst, src map[string]any) {
	for k, v := range src {
		if sv, ok := v.(map[string]any); ok {
			if dv, ok := dst[k].(map[string]any); ok {
				mergeValues(dv, sv)
				continue
			}
			copied := map[string]any{}
			mergeValues(copied, sv)
			dst[k] = copied
			continue
		}
		dst[k] = v
	}
}

// UmbrellaHelmArgv installs or upgrades the one release.
func UmbrellaHelmArgv(c kube.Cluster, u Umbrella, st Staged) []string {
	args := []string{"upgrade", "--install", u.Application, st.Dir}
	for _, f := range st.Values {
		args = append(args, "-f", f)
	}
	args = append(args, "--create-namespace", "--wait", "--timeout", "20m")
	return append([]string{"helm"}, c.Args(args...)...)
}

// PerServiceReleases lists the releases in the namespace that are the
// targets' own (from before the umbrella). Helm refuses to adopt resources
// owned by another release, so they must be uninstalled before the first
// umbrella install. The umbrella release itself is not listed.
func PerServiceReleases(c kube.Cluster, targets []Target, application string) ([]string, error) {
	if err := kube.Guard(c); err != nil {
		return nil, err
	}
	out, err := kube.Output("helm", c.Args("list", "-o", "json")...)
	if err != nil {
		return nil, fmt.Errorf("helm list: %v", err)
	}
	var releases []struct {
		Name string `json:"name"`
	}
	if err := json.Unmarshal(out, &releases); err != nil {
		return nil, fmt.Errorf("helm list: %v", err)
	}
	var names []string
	for _, t := range targets {
		for _, r := range releases {
			if r.Name == t.ChartName && r.Name != application {
				names = append(names, r.Name)
			}
		}
	}
	slices.Sort(names)
	return slices.Compact(names), nil
}

// UninstallArgv removes a per-service release (its resources are recreated
// by the umbrella).
func UninstallArgv(c kube.Cluster, release string) []string {
	return append([]string{"helm"}, c.Args("uninstall", release, "--wait")...)
}

// RestartArgv restarts a service's deployment so it picks up a re-imported
// image of the same tag (imagePullPolicy: Never) - the quick iteration
// after a code change, without a helm upgrade.
func RestartArgv(c kube.Cluster, t Target) [][]string {
	return [][]string{
		append([]string{"kubectl"}, c.KubectlArgs("rollout", "restart", "deployment/"+t.ChartName)...),
		append([]string{"kubectl"}, c.KubectlArgs("rollout", "status", "deployment/"+t.ChartName, "--timeout=11m")...),
	}
}

func joinNames(targets []Target) string {
	names := make([]string, 0, len(targets))
	for _, t := range targets {
		names = append(names, t.Project.Name)
	}
	return strings.Join(names, ", ")
}
